    internal static bool TryResolve(string name, out uint mask, out int[] ranges, out bool isBlock)
    {
        mask = 0;
        ranges = [];
        isBlock = false;
        switch (name)
        {
            case "Cc": mask = 1u << 14; return true;
            case "Cf": mask = 1u << 15; return true;
            case "Cn": mask = 1u << 29; return true;
            case "Co": mask = 1u << 17; return true;
            case "Cs": mask = 1u << 16; return true;
            case "C": mask = (1u << 14) | (1u << 15) | (1u << 16) | (1u << 17) | (1u << 29); return true;
            case "Ll": mask = 1u << 1; return true;
            case "Lm": mask = 1u << 3; return true;
            case "Lo": mask = 1u << 4; return true;
            case "Lt": mask = 1u << 2; return true;
            case "Lu": mask = 1u << 0; return true;
            case "L": mask = (1u << 0) | (1u << 1) | (1u << 2) | (1u << 3) | (1u << 4); return true;
            case "Mc": mask = 1u << 6; return true;
            case "Me": mask = 1u << 7; return true;
            case "Mn": mask = 1u << 5; return true;
            case "M": mask = (1u << 5) | (1u << 6) | (1u << 7); return true;
            case "Nd": mask = 1u << 8; return true;
            case "Nl": mask = 1u << 9; return true;
            case "No": mask = 1u << 10; return true;
            case "N": mask = (1u << 8) | (1u << 9) | (1u << 10); return true;
            case "Pc": mask = 1u << 18; return true;
            case "Pd": mask = 1u << 19; return true;
            case "Pe": mask = 1u << 21; return true;
            case "Po": mask = 1u << 24; return true;
            case "Ps": mask = 1u << 20; return true;
            case "Pf": mask = 1u << 23; return true;
            case "Pi": mask = 1u << 22; return true;
            case "P": mask = (1u << 18) | (1u << 19) | (1u << 20) | (1u << 21) | (1u << 22) | (1u << 23) | (1u << 24); return true;
