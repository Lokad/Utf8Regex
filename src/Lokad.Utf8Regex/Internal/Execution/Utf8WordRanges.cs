    public static bool IsWordChar(uint scalar)
    {
        var low = 0;
        var high = Ranges.Length - 1;
        while (low <= high)
        {
            var middle = low + ((high - low) >> 1);
            var range = Ranges[middle];
            if (scalar < (uint)range.Start)
            {
                high = middle - 1;
            }
            else if (scalar > (uint)range.End)
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }
